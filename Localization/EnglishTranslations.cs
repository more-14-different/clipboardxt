    public static bool ContainsHan(string? value) => !string.IsNullOrEmpty(value) && HanRegex.IsMatch(value);

    public static string Translate(string? source, bool english)
    {
        if (string.IsNullOrEmpty(source) || !english) return source ?? string.Empty;
        if (Exact.TryGetValue(source, out var exact)) return exact;
        if (AdditionalExact.TryGetValue(source, out exact)) return exact;

        var translated = TranslateAdditional(source, normalizePunctuation: false);
        foreach (var (chinese, replacement) in Fragments)
            translated = translated.Replace(chinese, replacement, StringComparison.Ordinal);
        return TranslateAdditional(translated, normalizePunctuation: true);
    }
